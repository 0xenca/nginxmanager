"""Real `nginx -t` against the generated configuration (skipped without nginx)."""
from conftest import HOST_FORM, needs_nginx

from nginxpanel import config, db, nginx

pytestmark = needs_nginx


def full_setup(client):
    client.post("/backends/new", {"name": "web", "method": "least_conn", "servers": "127.0.0.1:9001 weight=2\n[::1]:9002 backup",
                                  "max_fails": "3", "fail_timeout": "30s", "keepalive": "32"})
    client.post("/access/new", {"name": "office", "allow": "10.0.0.0/8", "deny": "10.6.6.6", "default_action": "deny",
                                "auth_users": "bob:password123", "satisfy": "any"})
    client.post("/certs/new", {"kind": "selfsigned", "name": "self", "domains": "app.example.com\n*.example.com"})
    bid = db.list_entities("backends", db.connect())[0]["id"]
    aid = db.list_entities("access_lists", db.connect())[0]["id"]
    cid = db.list_entities("certs", db.connect())[0]["id"]
    client.post("/hosts/new", {**HOST_FORM, "forward_mode": "backend", "backend_id": str(bid), "cert_id": str(cid),
                               "force_ssl": "on", "http2": "on", "hsts": "on", "access_list_id": str(aid),
                               "websocket": "on", "rate_limit": "on", "conn_limit": "20", "max_body": "100m",
                               "cache_mode": "static"})
    client.post("/hosts/new", {**HOST_FORM, "domains": "*.example.com", "forward_scheme": "https",
                               "upstream_ssl_verify": "on", "cert_id": str(cid), "cache_mode": "all"})
    client.post("/hosts/new", {**HOST_FORM, "domains": "old.example.com", "type": "redirect",
                               "redirect_url": "https://app.example.com", "redirect_code": "308", "preserve_path": "on"})
    client.post("/streams/new", {"name": "dns", "enabled": "on", "listen_ip": "", "listen_port": "5353",
                                 "protocol": "both", "targets": "127.0.0.1:53\n127.0.0.2:53 backup",
                                 "method": "least_conn", "connect_timeout": "5s", "proxy_timeout": "1m",
                                 "access_list_id": str(aid)})
    client.post("/security", {"default_behavior": "drop", "ipv6": "on", "client_max_body_size": "64m", "gzip": "on",
                              "trusted_proxies": "173.245.48.0/20", "waf_scanners": "on", "waf_probes": "on",
                              "waf_injection": "on", "waf_bad_methods": "on", "waf_empty_ua": "on",
                              "rate_limit_rps": "20", "blocklist": "203.0.113.0/24", "cache_keys_zone_mb": "50",
                              "cache_max_size": "2g", "le_email": "", "http_custom": ""})


def test_full_config_passes_nginx_t(client):
    full_setup(client)
    assert len(db.list_entities("hosts", db.connect())) == 3
    ok, out, warnings = nginx.apply(db.connect(), label="test")
    assert ok, out
    assert "syntax is ok" in out and "test is successful" in out
    assert (config.MANAGED_DIR / "snippets" / "waf_maps.conf").exists()
    assert "Generated by nginx-panel" in config.NGINX_CONF.read_text()


def test_invalid_custom_directive_is_rolled_back(client):
    client.post("/hosts/new", HOST_FORM)
    hid = db.list_entities("hosts", db.connect())[0]["id"]
    good_conf = config.NGINX_CONF.read_text()
    form = {**HOST_FORM, "custom_server": "this_directive_does_not_exist on;"}
    r = client.post(f"/hosts/{hid}/edit", form)
    body = r.page
    assert r.status_code == 400
    assert "nginx -t failed; the previous configuration has been restored." in body
    assert db.get_entity("hosts", hid, db.connect())["custom_server"] == ""      # DB change reverted
    assert config.NGINX_CONF.read_text() == good_conf                         # files restored
    assert "this_directive_does_not_exist" not in (config.MANAGED_DIR / "hosts" / f"host_{hid}.conf").read_text()


def test_backups_and_restore(client):
    client.post("/hosts/new", HOST_FORM)
    client.post("/hosts/new", {**HOST_FORM, "domains": "second.example.com"})
    backups = nginx.list_backups()
    assert len(backups) >= 2
    r = client.post("/system/restore", {"name": backups[0]})
    assert "Backup restored." in r.page


def test_system_test_button(client):
    client.post("/system/apply")
    r = client.post("/system/service/test")
    assert "test is successful" in r.page
